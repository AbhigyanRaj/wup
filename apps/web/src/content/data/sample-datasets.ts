import type { SampleDataset } from "../types";

/**
 * Sample collections used by the free tools and their worked examples.
 *
 * Values are MongoDB Extended JSON: {"$oid": ...} for ObjectIds and
 * {"$date": ...} for dates. scripts/verify-tool-examples.mjs seeds exactly
 * these documents into an in-memory MongoDB and runs every example against
 * them, so result previews in tools.ts must match what MongoDB returns.
 *
 * Amounts are in INR. All names and emails are fictional.
 */

